"""NOR56 source-free canonical batch-table, signed Ed25519 and replay tests.

Only toy sources and immutable earlier original NOR55 archive are used. The
new 60-source NOR56 fixture is not generated by these tests.
"""
from __future__ import annotations
import itertools,struct,unittest
from hashlib import sha256
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from research.nor46_exact_integer_trace import trace_verifier as nor46
from research.nor51_exact_r_crossover import algebra as native
from research.nor52_sparse_inverse import algebra as support
from research.nor55_compact_witness import codec as v1codec,envelope as v1
from research.nor56_batch_codec import codec_v2,signed_v2,cohort

def toy_source(stride:int):
    f=[1]+[0]*(6*stride)
    f[stride]=-2
    f[2*stride]=3
    return tuple(f)

def context_v2(f,stride,sequence=1,nonce="a"*64,source_id=None,root=None,
               session="nor56-source-free-toy",public_key=None):
    ref=native.native_single_inverse(f)
    return signed_v2.make_context_v2(
        source=f,stride=stride,
        source_sha256=source_id or sha256(b"NOR56/TOY/SOURCE").hexdigest(),
        expected_root_sha256=root or native.root(ref),
        session_id=session,sequence=sequence,nonce=nonce,public_key=public_key)

class ExactBatchCodecTests(unittest.TestCase):
    def test_exhaustive_small_finite_exact_full_inverse_and_signed_root(self):
        for stride in (1,4,8):
            for coefficients in itertools.product((-1,0,1,2),repeat=3):
                f=support.expand((1,)+coefficients,3*stride+1,stride)
                reference=native.native_single_inverse(f)
                old=v1codec.encode_full_supported(reference,stride)
                new=codec_v2.encode_full_supported(reference,stride)
                self.assertEqual(
                    codec_v2.decode_full_supported(new,len(f),stride),reference)
                self.assertEqual(
                    v1codec.decode_full_supported(old,len(f),stride),reference)
                ctx=context_v2(f,stride)
                signed=signed_v2.make_signed_envelope_v2(reference,ctx)
                self.assertEqual(
                    signed_v2.verify_signed_envelope_v2(
                        signed,ctx,v1.ReplayGuard()),
                    (reference,native.root(reference)))
        self.assertEqual(
            codec_v2.decode_reduced(codec_v2.encode_reduced((1,0,-2,257)),4),
            (1,0,-2,257))

    def test_4097_bit_and_signed_cap_and_strict_endianness(self):
        coefficients=(1,1<<4096,-(1<<4095),0)
        wire=codec_v2.encode_reduced(coefficients)
        self.assertEqual(codec_v2.decode_reduced(wire,len(coefficients)),
                         coefficients)
        maximum=(1,1<<32767,-(1<<32767))
        self.assertEqual(codec_v2.decode_reduced(
            codec_v2.encode_reduced(maximum),3),maximum)
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.encode_reduced((1,1<<32768))
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.encode_reduced((1,True))
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.encode_reduced((True,1))
        # Signed big-endian H table. Reversed endianness must be rejected
        # by the independently checked total width and unit.
        reversed_endian=codec_v2.MAGIC+b"\x01"+b"\x01\x00"+b"\x01"
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.decode_reduced(reversed_endian,1)

    def test_malicious_table_count_magnitude_and_full_support(self):
        m=codec_v2.MAGIC
        for bad in (
            m+b"\x81\x00"+struct.pack(">H",1)+b"\x01", # overlong count
            m+b"\x01"+b"\x00",                       # truncated table
            m+b"\x01"+struct.pack(">H",0x8000),       # negative zero
            m+b"\x01"+struct.pack(">H",0x8001)+b"\x01",# negative unit
            m+b"\x01"+struct.pack(">H",2)+b"\x00\x01",# nonminimal magnitude
            m+b"\x01"+struct.pack(">H",4097)+b"x",    # exceeds 4096
            m+b"\x01"+struct.pack(">H",1)+b"\x01\x00",# trailing byte
            m+b"\x01"+struct.pack(">H",1),            # missing magnitude
            m+b"\x02"+struct.pack(">H",1)+b"\x01",    # insufficient table
            b"N55C1"+b"\x01"+struct.pack(">H",1)+b"\x01" # downgrade magic
        ):
            with self.subTest(bad=bad[:16]),self.assertRaises((ValueError,TypeError)):
                codec_v2.decode_reduced(bad,1)
        f=toy_source(4)
        ref=native.native_single_inverse(f)
        bad=list(ref);bad[1]=1
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.encode_full_supported(tuple(bad),4)
        for stride in (0,2,3,7,True,"4"):
            with self.assertRaises((ValueError,TypeError)):
                codec_v2.encode_full_supported(ref,stride)
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.decode_full_supported(
                codec_v2.encode_full_supported(ref,4),len(f)+1,4)
        with self.assertRaises((ValueError,TypeError)):
            codec_v2.decode_full_supported(
                codec_v2.encode_full_supported(ref,4),True,4)

    def test_version_domain_downgrade_header_root_source_and_replay(self):
        f=toy_source(4)
        reference=native.native_single_inverse(f)
        ctx=context_v2(f,4)
        wire=signed_v2.make_signed_envelope_v2(reference,ctx)
        header,payload,sig,unsigned=v1.inspect_header(wire)
        self.assertEqual(header["payload_format"],signed_v2.FORMAT_V2)
        self.assertEqual(header["protocol"],signed_v2.PROTOCOL_V2)
        self.assertTrue(payload.startswith(codec_v2.MAGIC))
        self.assertEqual(
            signed_v2.verify_signed_envelope_v2(wire,ctx,v1.ReplayGuard()),
            (reference,native.root(reference)))
        guard=v1.ReplayGuard()
        signed_v2.verify_signed_envelope_v2(wire,ctx,guard)
        with self.assertRaises((ValueError,TypeError)):
            signed_v2.verify_signed_envelope_v2(wire,ctx,guard)
        prior_context=v1.make_context(
            source=f,source_sha256=ctx.source_sha256,stride=4,
            expected_root_sha256=ctx.expected_root_sha256,
            payload_format="compact-v1",session_id=ctx.session_id,
            sequence=ctx.sequence,nonce=ctx.nonce)
        previous_wire=v1.make_signed_envelope(reference,prior_context)
        with self.assertRaises((ValueError,TypeError)):
            signed_v2.verify_signed_envelope_v2(
                previous_wire,ctx,v1.ReplayGuard())
        with self.assertRaises((ValueError,TypeError)):
            v1.verify_signed_envelope(wire,prior_context,v1.ReplayGuard())
        other_source=list(f);other_source[4]=-3
        cases=[
            context_v2(f,4,nonce="b"*64),
            context_v2(f,4,source_id="b"*64),
            context_v2(f,4,root="0"*64),
            context_v2(f,4,session="other-session"),
            context_v2(tuple(other_source),4),
            context_v2(
                f,4,public_key=Ed25519PrivateKey.from_private_bytes(
                    b"z"*32).public_key())
        ]
        for other in cases:
            with self.subTest(ctx=other.source_sha256),self.assertRaises((ValueError,TypeError)):
                signed_v2.verify_signed_envelope_v2(
                    wire,other,v1.ReplayGuard())
        corrupted=(
            wire[:-1]+bytes([wire[-1]^1]),wire[:-1],
            b"BAD!"+wire[4:],
            wire[:-64]+b"\x00"*64,
            wire+b"\x00"
        )
        for raw in corrupted:
            with self.assertRaises((ValueError,TypeError)):
                signed_v2.verify_signed_envelope_v2(
                    raw,ctx,v1.ReplayGuard())
        incorrect=list(reference);incorrect[8]+=1
        forged=signed_v2.make_signed_envelope_v2(incorrect,ctx)
        with self.assertRaises((ValueError,TypeError)):
            signed_v2.verify_signed_envelope_v2(
                forged,ctx,v1.ReplayGuard())
        # Rejected attempt must not consume a verifier-issued challenge.
        self.assertEqual(
            signed_v2.verify_signed_envelope_v2(
                wire,ctx,v1.ReplayGuard()),(reference,native.root(reference)))

    def test_staged_sequence_and_original_55_negative_archive(self):
        f=toy_source(8)
        ref=native.native_single_inverse(f)
        guard=v1.ReplayGuard()
        for i in range(1,6):
            ctx=context_v2(f,8,sequence=i,nonce=f"{i:064x}")
            wire=signed_v2.make_signed_envelope_v2(ref,ctx)
            self.assertEqual(signed_v2.verify_signed_envelope_v2(wire,ctx,guard),
                             (ref,native.root(ref)))
        from research.nor55_compact_witness import original_archive_audit
        assert original_archive_audit.audit()["verdict"]=="FAIL (4/5)"
        self.assertEqual(cohort.REGISTERED,
                         "b186ee7478f27230478b099d7091b25817839464")
        self.assertEqual(len(cohort.historical_ids()),288)
        self.assertEqual(len(cohort.REPS)*len(cohort.LENGTHS)*
                         len(cohort.PROFILES)*len(cohort.FAMILIES),60)

if __name__=="__main__":
    unittest.main()

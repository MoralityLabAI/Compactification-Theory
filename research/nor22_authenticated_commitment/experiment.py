"""NOR-22: authenticated modular target commitments and information boundaries.

The public verifier computes its unique candidate output ONLY from full
public demonstrations and the public query INPUT. Separately authenticated
target-dependent field evaluations provide additional information; they
are neither derivable from the public sources nor assumed freely available.

A sealed grader reconstructs the planted native program and each of four
counterfactual hidden future targets after all source and policy choices
have been frozen. Honest target fingerprints are generated by an explicit
trusted publisher during fixture creation; forged fingerprints are an
untrusted negative control.

Preregistered in README.md before fresh source generation. Every shift
kind shares the same public input digest per source and is NOT counted
as a new independent source.
"""
from __future__ import annotations

import argparse
from collections import Counter
from hashlib import sha256
import json
from pathlib import Path
import random
import sys

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0,str(ROOT))

from research.rrc_compactification import compound25 as corpus
from research.nor21_degree_scaling import experiment as nor21

SCHEMA="nor22.authenticated_modular_target_commitment.v1"
FIXTURE_SCHEMA="nor22.public_with_explicit_authenticated_target_commitments.v1"
FRESH_OFFSET=94322000
REPLICATES=2
DEGREES=(512,1024)
FAMILIES=("wide_dense_small","wide_sparse_small","wide_rational_short")
SOURCE_COUNT=REPLICATES*len(DEGREES)*len(FAMILIES)
WORLD_KINDS=("valid","unit_shift","p_shift","product_shift")
ARMS=("public_only","trusted_p","trusted_pq","forged_pq")
P=65537
Q=65521
R=3
SHIFT={"valid":0,"unit_shift":1,"p_shift":P,"product_shift":P*Q}
MAX_ATTEMPTS=100
EXACT_CORRECTNESS_MATRIX={
    "valid":{"public_only":"correct","trusted_p":"correct",
             "trusted_pq":"correct","forged_pq":"correct"},
    "unit_shift":{"public_only":"false_accept","trusted_p":"abstain",
                  "trusted_pq":"abstain","forged_pq":"false_accept"},
    "p_shift":{"public_only":"false_accept","trusted_p":"false_accept",
               "trusted_pq":"abstain","forged_pq":"false_accept"},
    "product_shift":{"public_only":"false_accept","trusted_p":"false_accept",
                     "trusted_pq":"false_accept","forged_pq":"false_accept"},
}


def canonical(obj):
    return (json.dumps(obj,indent=2,sort_keys=True,ensure_ascii=True)+"\n").encode()


def source_seed(rep,degree,family):
    if rep not in (0,1) or degree not in DEGREES or family not in FAMILIES:
        raise ValueError("not a registered NOR22 source")
    return (corpus.SEED+FRESH_OFFSET+1000003*rep+
            100009*DEGREES.index(degree)+10007*FAMILIES.index(family))


def fingerprint(coeffs,modulus):
    """Exact Horner polynomial evaluation at r=3 modulo a small prime."""
    if modulus not in (P,Q):
        raise ValueError("not a registered commitment modulus")
    value=0
    for coefficient in reversed(coeffs):
        value=(R*value+coefficient)%modulus
    return value


def hash_target(coeffs):
    return sha256(json.dumps(coeffs,separators=(",",":")).encode()).hexdigest()


def shifted_future(future,kind):
    if kind not in WORLD_KINDS:
        raise ValueError("unknown counterfactual target world")
    y=list(future)
    y[-1]+=SHIFT[kind]
    return tuple(y)


def public_digest(c,degree):
    return nor21.public_digest(c,degree)


def generate_new_source(rep,degree,family,known=None):
    """Draw a unique public case, preserving the private program ONLY
    in the source-generation return value. No private program is
    serialized in a fixture or passed to the public policy.
    """
    rng=random.Random(source_seed(rep,degree,family))
    query_degree=3*degree//2
    for attempt in range(MAX_ATTEMPTS):
        program=nor21.new_header_program(rng)
        demos=tuple((f:=nor21.public_source(rng,family,query_degree),
                     corpus.execute(f,program)) for _ in range(2))
        query=nor21.public_source(rng,family,query_degree)
        case=corpus.Case(
            f"nor22-r{rep}-d{degree}-{family}-{attempt}",family,
            demos,query,(),None)
        headers=corpus.possible_headers(case)
        if len(headers)!=1:
            continue
        header=headers[0]
        if (header.base,header.delay,header.spacing,
                header.amplitude)!=program[:4]:
            continue
        digest=public_digest(case,degree)
        if known is not None and digest in known:
            continue
        mask=nor21.native_mask(case,header,degree)
        if mask==0:
            continue
        output_candidates=nor21.candidate_predictions(
            query,header,query_degree)
        unique={output_candidates[j] for j in range(16) if mask&(1<<j)}
        if len(unique)!=1:
            continue
        planted_class=4*corpus.OPS.index(program[4])+corpus.OPS.index(
            program[5])
        if not (mask&(1<<planted_class)):
            raise AssertionError("actual generator not publicly compatible")
        if known is not None:
            known.add(digest)
        return case,header,program,attempt,digest,mask
    raise RuntimeError("NOR22 source rejected all 100 attempts")


def make_fixture():
    known=set()
    cases=[]
    for rep in range(REPLICATES):
        for degree in DEGREES:
            for family in FAMILIES:
                c,header,program,attempt,digest,mask=generate_new_source(
                    rep,degree,family,known)
                real_target=corpus.execute(c.query,program)
                worlds={}
                for kind in WORLD_KINDS:
                    target=shifted_future(real_target,kind)
                    worlds[kind]={
                        "trusted_eval_mod_65537":fingerprint(target,P),
                        "trusted_eval_mod_65521":fingerprint(target,Q),
                    }
                cases.append({
                    "replicate":rep,"observation_degree":degree,
                    "query_degree":3*degree//2,"family":family,
                    "source_seed":source_seed(rep,degree,family),
                    "selected_attempt":attempt,
                    "full_public_input_sha256":digest,
                    "public_header":{
                        "base":header.base,"delay":header.delay,
                        "spacing":header.spacing,
                        "amplitude":header.amplitude},
                    "demos":[[list(f[:degree+1]),list(y[:degree+1])]
                              for f,y in c.demos],
                    "public_query_input":list(c.query),
                    "original_public_accept_mask":mask,
                    "trusted_target_commitments_by_counterfactual_world":worlds,
                })
    assert len(cases)==SOURCE_COUNT
    assert len({z["full_public_input_sha256"] for z in cases})==SOURCE_COUNT
    assert Counter(c["observation_degree"] for c in cases)=={512:6,1024:6}
    assert Counter(c["replicate"] for c in cases)=={0:6,1:6}
    assert Counter(c["family"] for c in cases)=={
        f:4 for f in FAMILIES}
    return {
        "schema":FIXTURE_SCHEMA,
        "registration_offset":FRESH_OFFSET,
        "registered_moduli":[P,Q],
        "registered_polynomial_evaluation_point":R,
        "registered_target_world_kinds":list(WORLD_KINDS),
        "distinct_public_sources":SOURCE_COUNT,
        "public_sources_include_extra_target_dependent_attested_values":True,
        "target_output_arrays_and_generating_programs_absent":True,
        "trusted_publisher_authenticity_is_an_explicit_assumption":True,
        "cases":cases,
    }


def load_fixture(path):
    raw=Path(path).read_bytes()
    data=json.loads(raw)
    assert data["schema"]==FIXTURE_SCHEMA
    assert data["registration_offset"]==FRESH_OFFSET
    assert data["registered_moduli"]==[P,Q]
    assert data["registered_polynomial_evaluation_point"]==R
    assert data["registered_target_world_kinds"]==list(WORLD_KINDS)
    assert data["distinct_public_sources"]==SOURCE_COUNT
    assert data["public_sources_include_extra_target_dependent_attested_values"]
    assert data["target_output_arrays_and_generating_programs_absent"]
    assert data["trusted_publisher_authenticity_is_an_explicit_assumption"]
    assert len(data["cases"])==SOURCE_COUNT
    assert len({c["full_public_input_sha256"] for c in data["cases"]})==SOURCE_COUNT
    return data,sha256(raw).hexdigest()


def public_case(row):
    d=row["observation_degree"]
    assert d in DEGREES and row["query_degree"]==3*d//2
    head=row["public_header"]
    header=corpus.Header(head["base"],head["delay"],
                         head["spacing"],head["amplitude"])
    demos=tuple((tuple(f),tuple(y)) for f,y in row["demos"])
    source=tuple(row["public_query_input"])
    assert len(demos)==2 and all(
        len(f)==len(y)==d+1 for f,y in demos)
    assert len(source)==row["query_degree"]+1 and source[0]==1
    c=corpus.Case("nor22-public",row["family"],demos,source,(),None)
    assert c.future==() and c.program is None
    assert public_digest(c,d)==row["full_public_input_sha256"]
    return c,header


def select_public_candidate(public,header,degree,query_degree):
    """Completely target-independent public selection, one time per source."""
    mask=nor21.native_mask(public,header,degree)
    assert mask>0
    candidate_outputs=nor21.candidate_predictions(
        public.query,header,query_degree)
    distinct={candidate_outputs[j]
              for j in range(16) if mask&(1<<j)}
    assert len(distinct)==1
    chosen=next(j for j in range(16) if mask&(1<<j))
    predicted=candidate_outputs[chosen]
    return {
        "public_mask":mask,
        "unique_public_prediction":True,
        "chosen_class":chosen,
        "predicted_output":predicted,
        "predicted_output_sha256":hash_target(predicted),
        "self_eval_mod_65537":fingerprint(predicted,P),
        "self_eval_mod_65521":fingerprint(predicted,Q),
    }


def choose_with_commitment(public_proposal,anchor,arm):
    """No access to the target world label or planted program.

    The anchor is a *new target-dependent input* for the trusted arms.
    Forged anchors are deliberately untrusted and synthesized from the
    candidate prediction, proving self-reference adds no information.
    """
    if arm not in ARMS:
        raise ValueError("unregistered NOR22 policy")
    p=public_proposal["self_eval_mod_65537"]
    q=public_proposal["self_eval_mod_65521"]
    if arm=="public_only":
        agrees=True
        information_bits=0
        source="none"
    elif arm=="forged_pq":
        agrees=(p==p and q==q)
        information_bits=0
        source="untrusted_self_generated"
    else:
        if set(anchor)!={
            "trusted_eval_mod_65537","trusted_eval_mod_65521"}:
            raise ValueError("expected explicit trusted target fingerprint")
        agrees=(p==anchor["trusted_eval_mod_65537"])
        if arm=="trusted_pq":
            agrees=agrees and q==anchor["trusted_eval_mod_65521"]
        information_bits=17 if arm=="trusted_p" else 33
        source="assumed_authenticated_target_publisher"
    return {
        "arm":arm,
        "accepted":bool(agrees),
        "chosen_class":public_proposal["chosen_class"] if agrees else None,
        "status":"candidate_emitted" if agrees else "modular_mismatch_abstain",
        "extra_trusted_target_dependent_modular_values":(
            0 if arm in ("public_only","forged_pq") else
            (1 if arm=="trusted_p" else 2)),
        "upper_bound_bits_of_attested_moduli":information_bits,
        "commitment_provenance":source,
    }


def postchoice_grader(row,selected):
    """Only here are native true programs and true future outputs rebuilt.

    The first stage's public selections must be fully frozen beforehand.
    This regenerates each chosen source from its independent seed and
    checks its public digest before touching target truth.
    """
    rep=row["replicate"]
    d=row["observation_degree"]
    family=row["family"]
    case,h,program,attempt,digest,mask=generate_new_source(
        rep,d,family)
    assert attempt==row["selected_attempt"]
    assert digest==row["full_public_input_sha256"]
    assert mask==row["original_public_accept_mask"]
    real_target=corpus.execute(case.query,program)
    truth_by_world={
        kind:shifted_future(real_target,kind) for kind in WORLD_KINDS}
    out={}
    predicted=selected["predicted_output"]
    assert predicted==real_target, "publicly unique prediction must match planted program"
    for kind in WORLD_KINDS:
        truth=truth_by_world[kind]
        expected_anchor={
            "trusted_eval_mod_65537":fingerprint(truth,P),
            "trusted_eval_mod_65521":fingerprint(truth,Q),
        }
        assert expected_anchor==row[
            "trusted_target_commitments_by_counterfactual_world"][kind]
        verdicts={}
        for arm in ARMS:
            selection=selected["world_choices"][kind][arm]
            emitted=selection["chosen_class"] is not None
            correct=emitted and predicted==truth
            verdicts[arm]={
                **selection,
                "future_correct":bool(correct),
                "false_accept":bool(emitted and not correct),
                "abstained":not emitted,
            }
            expected=EXACT_CORRECTNESS_MATRIX[kind][arm]
            status=("correct" if correct else
                    "false_accept" if emitted else "abstain")
            assert status==expected,(kind,arm,status,expected)
        out[kind]={
            "target_sha256_sealed_grader_only":hash_target(truth),
            "authentic_commitments":expected_anchor,
            "same_complete_public_input_sha256":digest,
            "counterfactual_target_differs_from_valid":kind!="valid",
            "arms":verdicts,
        }
    return out


def run(fixture_path):
    source,fixture_sha=load_fixture(fixture_path)
    public_frozen=[]
    for row in source["cases"]:
        case,header=public_case(row)
        proposal=select_public_candidate(
            case,header,row["observation_degree"],row["query_degree"])
        assert proposal["public_mask"]==row["original_public_accept_mask"]
        worlds={}
        for kind in WORLD_KINDS:
            anchor=row["trusted_target_commitments_by_counterfactual_world"][kind]
            worlds[kind]={
                arm:choose_with_commitment(proposal,anchor,arm) for arm in ARMS}
        public_frozen.append({
            "row":row,
            "public_mask":proposal["public_mask"],
            "chosen_class":proposal["chosen_class"],
            "predicted_output_sha256":proposal["predicted_output_sha256"],
            "predicted_modular_commitments":{
                "eval_mod_65537":proposal["self_eval_mod_65537"],
                "eval_mod_65521":proposal["self_eval_mod_65521"],
            },
            "world_choices":worlds,
            "predicted_output":proposal["predicted_output"],
        })
    # Only after every policy selection has been frozen may hidden
    # future truth and the private planted program be regenerated.
    records=[]
    for frozen in public_frozen:
        row=frozen["row"]
        grade=postchoice_grader(row,frozen)
        records.append({
            "replicate":row["replicate"],
            "observation_degree":row["observation_degree"],
            "query_degree":row["query_degree"],
            "family":row["family"],
            "full_public_input_sha256":row["full_public_input_sha256"],
            "original_public_accept_mask":frozen["public_mask"],
            "chosen_class":frozen["chosen_class"],
            "predicted_output_sha256":frozen["predicted_output_sha256"],
            "predicted_modular_commitments":frozen[
                "predicted_modular_commitments"],
            "worlds":grade,
        })
    counts={
        kind:{arm:Counter() for arm in ARMS} for kind in WORLD_KINDS}
    for row in records:
        for kind in WORLD_KINDS:
            for arm in ARMS:
                choice=row["worlds"][kind]["arms"][arm]
                counts[kind][arm]["correct"]+=choice["future_correct"]
                counts[kind][arm]["false_accept"]+=choice["false_accept"]
                counts[kind][arm]["abstain"]+=choice["abstained"]
    aggregate={
        kind:{arm:dict(counts[kind][arm]) for arm in ARMS}
        for kind in WORLD_KINDS}
    for kind in WORLD_KINDS:
        for arm in ARMS:
            expected=EXACT_CORRECTNESS_MATRIX[kind][arm]
            assert aggregate[kind][arm][expected]==SOURCE_COUNT
            assert sum(aggregate[kind][arm].values())==SOURCE_COUNT
    return {
        "schema":SCHEMA,
        "fixture_schema":FIXTURE_SCHEMA,
        "fixture_sha256":fixture_sha,
        "registered_moduli":[P,Q],
        "registered_evaluation_point":R,
        "distinct_public_source_cases":SOURCE_COUNT,
        "counterfactual_target_world_records":SOURCE_COUNT*len(WORLD_KINDS),
        "public_verification_performed_once_per_source":True,
        "all_source_decisions_frozen_before_private_program_and_target_replay":True,
        "all_target_dependent_commitments_explicitly_trusted_or_forged":True,
        "public_program_family": "RRC25 base plus 16 ordered U/V templates",
        "world_kinds":list(WORLD_KINDS),
        "arms":list(ARMS),
        "source_records":records,
        "registered_exact_matrix":EXACT_CORRECTNESS_MATRIX,
        "observed_matrix":aggregate,
        "all_registered_outcomes_match":True,
        "scope":{
            "target_commitments_are_extra_target_dependent_information":True,
            "trusted_target_publisher_is_required_for_authentic_modular_checks":True,
            "rejected_fingerprint_mismatch_proves_wrong_prediction":True,
            "matching_modular_fingerprints_not_sufficient_for_correctness":True,
            "forged_commitment_is_untrusted_negative_control":True,
            "target_program_identity_never_passed_to_public_selection":True,
            "target_truth_replayed_after_frozen_decisions":True,
            "same_source_multiple_worlds_not_independent_cases":True,
            "no_claim_of_collision_resistant_authentication":True,
        },
    }


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--make-fixture",type=Path)
    parser.add_argument("--fixture",type=Path)
    parser.add_argument("--out",type=Path)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    if args.make_fixture:
        data=make_fixture()
        args.make_fixture.parent.mkdir(parents=True,exist_ok=True)
        args.make_fixture.write_bytes(canonical(data))
        print("NOR22 PUBLIC SOURCE AND AUTHENTIC COMMITMENTS FIXTURE SEALED",
              len(data["cases"]),sha256(args.make_fixture.read_bytes()).hexdigest())
        return
    if not args.fixture:
        parser.error("--make-fixture or --fixture required")
    result=run(args.fixture)
    if args.check:
        assert result["all_registered_outcomes_match"]
        assert result["counterfactual_target_world_records"]==48
        assert len(result["source_records"])==12
    encoded=canonical(result)
    if args.out:
        args.out.parent.mkdir(parents=True,exist_ok=True)
        args.out.write_bytes(encoded)
    else:
        print(encoded.decode(),end="")


if __name__=="__main__":
    main()

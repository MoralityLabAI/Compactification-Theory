"""NOR-07T: rigorous recentered tube for a strongly nonnormal trained GRU.

This validates D(F^L) uniformly on a Euclidean ball without interval-box
wrapping across L steps. It uses exact rational nominal Jacobians and
source-verified global Hessian M. The variation-of-constants bounds retain
the *norms of contiguous nominal Jacobian products*, rather than replacing
them by products of one-step norms. This is essential for nonnormal dynamics
whose single-step norm can exceed one while a long product contracts.

Scope: exact-real map generated by the frozen decimal-rational RRC25 weights;
numeric floats in the JSON output are descriptive only.
"""
from __future__ import annotations

from fractions import Fraction as Q

# Match the source module identity used by invariant_ball.py and NOR-07.
from trained_gru_cert import (
    Interval, N, ZERO, ONE, SCALE,
    gates, jacobian_interval, hessian_bound, rational_center,
    radius_upper, sqrt_upper, round_rational, ceil_rational, get_weights,
)


def identity():
    return [[Q(int(i == j)) for j in range(N)] for i in range(N)]


def matrix_product(A, B):
    return [[sum((A[i][k]*B[k][j] for k in range(N)), ZERO)
             for j in range(N)] for i in range(N)]


def frobenius_upper(A):
    return sqrt_upper(sum((x*x for row in A for x in row), ZERO))


def point_jacobian(weights, center):
    ji = jacobian_interval(weights, center)
    J = [[round_rational((x.lo+x.hi)/2) for x in row] for row in ji]
    err = sqrt_upper(sum((
        max(abs(x.lo-c), abs(x.hi-c))**2
        for row, middles in zip(ji,J,strict=True)
        for x,c in zip(row,middles,strict=True)),ZERO))
    return J, err


def nominal_trace(weights, center, length):
    if length < 1 or len(center) != N:
        raise ValueError("length must be positive and center 12-dimensional")
    c = list(center)
    states = [c]
    jacobians, point_j_err, step_residuals = [], [], []
    for _ in range(length):
        if any(abs(x) >= ONE for x in c):
            raise AssertionError("nominal center left invariant open cube")
        J, eps = point_jacobian(weights, c)
        jacobians.append(J)
        point_j_err.append(eps)
        box = gates(weights, [Interval.point(x) for x in c])[0]
        c = rational_center(box)
        e = radius_upper(box, c)
        step_residuals.append(e)
        states.append(c)
    return states, jacobians, point_j_err, step_residuals


def segment_norms(jacobians):
    """Upper norms C[j,k]>=||J[j-1] ... J[k]||_2.

    C[j,j]=1 exactly. Products are taken in chronological chain-rule
    order and computed entirely over rationals.
    """
    length=len(jacobians)
    products={(0,0):identity()}
    norms={(0,0):ONE}
    for end in range(1,length+1):
        products[(end,end)]=identity()
        norms[(end,end)]=ONE
        for start in range(end):
            prev = products[(end-1,start)]
            product = matrix_product(jacobians[end-1],prev)
            products[(end,start)]=product
            norms[(end,start)]=frobenius_upper(product)
    return products,norms


def recentered_tube(weights, center, radius, length):
    """Uniform real nonlinear block derivative bound on B(center,radius).

    For a nominal orbit c_j, let J_j be a rational midpoint matrix,
    and e_j enclose ||F(c_j)-c_(j+1)||. Every true orbit starting
    within radius r obeys

      delta_j <= ||P[j,0]|| r
                 + sum_{k<j} ||P[j,k+1]||*
                       (e_k+point_J_error_k*delta_k+M*delta_k^2/2).

    True product A_j=D(F^j)(x) satisfies
      ||A_j-P[j,0]|| <= sum_{k<j} ||P[j,k+1]||
          * (point_J_error_k + M*delta_k)
          * (||P[k,0]||+derivative_error_k).

    These are variation-of-constants identities plus Taylor and Hessian
    estimates. They preserve cancellation across nonnormal nominal powers.
    """
    if radius < 0 or len(center) != N or length < 1:
        raise ValueError("invalid ball or length")
    if any(abs(x)+radius >= ONE for x in center):
        raise ValueError("initial ball must lie in the invariant unit cube")
    M = hessian_bound(weights)
    states, js, point_j_err, step_e = nominal_trace(weights,center,length)
    products,norms = segment_norms(js)
    delta=[radius]
    derivative_error=[ZERO]
    forcing=[]
    for j in range(1,length+1):
        # All earlier delta values are certified before constructing delta_j.
        w = [step_e[k]+point_j_err[k]*delta[k]+M*delta[k]*delta[k]/2
             for k in range(j)]
        forcing.extend(w[len(forcing):])
        radius_j = norms[(j,0)]*radius + sum(
            (norms[(j,k+1)]*w[k] for k in range(j)), ZERO)
        # If an intermediate bound escapes the convex invariant cube,
        # the global Hessian estimate still applies to its actual orbit:
        # all actual states remain in the cube, and their centers are
        # in the cube; the segments joining them therefore remain there.
        delta.append(ceil_rational(radius_j,SCALE))

        derivative_j=sum((
            norms[(j,k+1)]*
            (point_j_err[k]+M*delta[k])*
            (norms[(k,0)]+derivative_error[k])
            for k in range(j)),ZERO)
        derivative_error.append(ceil_rational(derivative_j,SCALE))

    K=ceil_rational(norms[(length,0)]+derivative_error[length],SCALE)
    # The nominal end-center is exact rational. A separate point
    # enclosure is obtained by recomputing delta_j with initial zero.
    point_delta=[ZERO]
    for j in range(1,length+1):
        dj = sum((norms[(j,k+1)]*
                  (step_e[k]+point_j_err[k]*point_delta[k]+
                   M*point_delta[k]*point_delta[k]/2)
                  for k in range(j)),ZERO)
        point_delta.append(ceil_rational(dj,SCALE))
    point_center_gap=sqrt_upper(sum(
        ((x-y)**2 for x,y in zip(states[-1],center,strict=True)),ZERO))
    s = ceil_rational(point_center_gap+point_delta[-1],SCALE)

    return {
        "certification_method":"rational recentered nominal Jacobians; Volterra remainder with global analytic Hessian bound",
        "block_length":length,
        "initial_radius_fraction":str(radius),
        "global_one_step_hessian_upper_fraction":str(M),
        "block_operator_norm_upper_fraction":str(K),
        "block_operator_norm_upper_float":float(K),
        "nominal_product_frobenius_upper_fraction":str(norms[(length,0)]),
        "block_derivative_variation_upper_fraction":str(derivative_error[length]),
        "center_residual_upper_fraction":str(s),
        "center_residual_upper_float":float(s),
        "last_nominal_center_gap_fraction":str(point_center_gap),
        "last_point_shadowing_error_fraction":str(point_delta[-1]),
        "max_tube_radius_upper_fraction":str(max(delta)),
        "max_point_jacobian_error_fraction":str(max(point_j_err)),
        "point_center_literals":[str(x) for x in states[-1]],
        "invariance_margin_fraction":str(radius-s-K*radius),
        "contracting_invariant_ball":K<ONE and s+K*radius<=radius,
    }

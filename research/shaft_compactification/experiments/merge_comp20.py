"""Merge SHAFT-COMP-20 per-seed calibration and held-out receipts.

Inputs: the eight original JSON files generated by persistent_goal_control.py.
The calibration threshold file must be the locked prior GitHub receipt.
No retraining occurs. Test outcomes are never used to select a new threshold.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from research.shaft_compactification.experiments.architecture_vocab_transfer import auc

ASSIGN={
 'repeat_toggle':{'calibration':[2001,2002],'heldout':[2003,2004]},
 'successor_toggle':{'calibration':[2011,2012],'heldout':[2013,2014]}}
FEATURES=('goal','duplicate','history','goal_norm','duplicate_norm','history_norm','distance')

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def measure(rows):
    rows=[r for r in rows if r['eligible']]
    y=[r['native_delayed_divergence'] for r in rows]
    metrics={name:auc([r[name] for r in rows],y) for name in FEATURES}
    return {'eligible':len(rows),'positives':sum(y),'negatives':len(rows)-sum(y),
            'oracle_positives':sum(r['oracle_delayed_divergence'] for r in rows),
            'oracle_native_agreement':round(sum(r['native_delayed_divergence']==
                r['oracle_delayed_divergence'] for r in rows)/max(1,len(rows)),6),
            'auc':{k:None if v is None else round(v,6) for k,v in metrics.items()}}

def pair_counts(rows,feature):
    positives=[r[feature] for r in rows if r['eligible'] and r['native_delayed_divergence']]
    negatives=[r[feature] for r in rows if r['eligible'] and not r['native_delayed_divergence']]
    if not positives or not negatives:return None
    diff=np.array(positives)[:,None]-np.array(negatives)[None,:]
    return {'positive':len(positives),'negative':len(negatives),
            'wins':int((diff>0).sum()),'ties':int((diff==0).sum())}

def operating(rows,key,cut):
    e=[r for r in rows if r['eligible']]
    p=[r for r in e if r['native_delayed_divergence']]
    n=[r for r in e if not r['native_delayed_divergence']]
    tp=sum(r[key]>cut for r in p);fp=sum(r[key]>cut for r in n)
    return {'threshold':cut,'negatives':len(n),'positives':len(p),'tp':tp,'fp':fp,
            'tpr':round(tp/len(p),6) if p else None,
            'fpr':round(fp/len(n),6) if n else None}

def inference(heldout,n_iter=1000):
    e=[r for r in heldout if r['eligible']]
    y=np.asarray([r['native_delayed_divergence'] for r in e])
    history=np.asarray([r['history'] for r in e],float)
    goal=np.asarray([r['goal'] for r in e],float)
    groups={}
    for i,r in enumerate(e):
        groups.setdefault((r['family'],r['seed'],r['depth']),[]).append(i)
    observed=auc(history,y)-auc(goal,y)
    rng=np.random.default_rng(202020)
    permutations=[]
    for _ in range(n_iter):
        shuffled=y.copy()
        for index in groups.values():
            shuffled[index]=rng.permutation(shuffled[index])
        permutations.append(auc(history,shuffled)-auc(goal,shuffled))
    center=float(np.mean(permutations))
    p=(1+sum(abs(v-center)>=abs(observed-center)-1e-12
             for v in permutations))/(1+n_iter)
    deltas=[]
    for _ in range(n_iter):
        index=np.concatenate([rng.choice(g,len(g),replace=True)
                              for g in groups.values()])
        a=auc(history[index],y[index]);b=auc(goal[index],y[index])
        if a is not None and b is not None:deltas.append(a-b)
    lo,hi=np.quantile(deltas,[.025,.975])
    return {'primary_delta_auc':round(observed,6),
            'bootstrap95':[round(float(lo),6),round(float(hi),6)],
            'bootstrap_valid':len(deltas),'permutations':n_iter,
            'permutation_null_mean':round(center,6),
            'permutation_p_two_sided':round(float(p),6)}

def run(raw_dir,threshold_file):
    frozen=json.loads(Path(threshold_file).read_text())
    assert frozen['phase']=='calibration_thresholds'
    expected={(fam,phase,seed) for fam,assignment in ASSIGN.items()
              for phase,seeds in assignment.items() for seed in seeds}
    all_rows={'calibration':[],'heldout':[]}
    models={}
    seen=set()
    for family,assignment in ASSIGN.items():
        for phase,seeds in assignment.items():
            for seed in seeds:
                path=Path(raw_dir)/f'{phase}_{family}_{seed}.json'
                rec=json.loads(path.read_text())
                assert rec['family']==family and rec['phase']==phase and rec['seed']==seed
                assert rec['registration_commit']==frozen['registration_commit']
                assert rec['training_steps']==2400 and rec['per_goal']==8
                rows=[{**x,'family':family,'seed':seed,'phase':phase} for x in rec['rows']]
                all_rows[phase].extend(rows)
                seen.add((family,phase,seed))
                models[str(seed)]={'family':family,'phase':phase,
                    'accuracy_d12':rec['accuracy_d12'],
                    'accuracy_d32':rec['accuracy_d32'],
                    'model_sha256':rec['base_model_sha256'],
                    'full_receipt_sha256':sha(path)}
    assert seen==expected
    cal,held=all_rows['calibration'],all_rows['heldout']
    scores={x:measure(rows) for x,rows in all_rows.items()}
    family={fam:measure([r for r in held if r['family']==fam]) for fam in ASSIGN}
    for f,m in family.items():
        m['history_minus_goal']=round(m['auc']['history']-m['auc']['goal'],6)
    thresholds=frozen['pooled_thresholds']
    operating_points={fam:{name:operating([r for r in held if r['family']==fam],
                    name,thresholds[name]) for name in ('goal','duplicate','history')}
                 for fam in ASSIGN}
    operating_points['combined']={name:operating(held,name,thresholds[name])
                                  for name in ('goal','duplicate','history')}
    confidence=inference(held)
    return {'experiment':'SHAFT-COMP-20',
            'registration_commit':frozen['registration_commit'],
            'calibration_lock_sha256':sha(threshold_file),
            'calibration':scores['calibration'],'heldout':scores['heldout'],
            'per_family_heldout':family,'models':models,
            'fixed_thresholds':thresholds,'operating_points':operating_points,
            'uncertainty':confidence,
            'supported_neural_transfer':bool(confidence['bootstrap95'][0]>0 and
                     all(m['history_minus_goal']>0 for m in family.values())),
            'fpr_transfer_pass':all(operating_points[f]['history']['fpr']<=.15 for f in ASSIGN),
            'eligible_primary_pair_counts':{phase:{name:pair_counts(rows,name)
                     for name in FEATURES} for phase,rows in all_rows.items()}}

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--raw-dir',type=Path,required=True)
    p.add_argument('--calibration-file',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    result=run(a.raw_dir,a.calibration_file)
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(result,sort_keys=True,indent=2)+'\n')
    print(json.dumps({'heldout':result['heldout'],
                      'uncertainty':result['uncertainty']},indent=2))

if __name__=='__main__':
    main()

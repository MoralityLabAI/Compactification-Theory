"""RRC-20 calibration and genuinely new compositional source-generator roster.

The graph language and exact semantics are frozen from RRC-18.  New test
families are generated by combining source rules, not by inventing operators.
The train-only entry point never constructs any test family.
"""
from __future__ import annotations
from dataclasses import replace
from hashlib import sha256
import json
import random

try:
    from . import family19 as old, topology16 as t, graph11 as g
except ImportError:
    import family19 as old
    import topology16 as t
    import graph11 as g

SEED=2026111020
KNOWN=('signed','product','sparse')
NOVEL=('twisted_product','rational_product','mixed_signed_product','cubic_sparse')
FAMILIES=KNOWN+NOVEL
KNOWN_PER_TOPOLOGY=12
NOVEL_PER_TOPOLOGY=24
NEGATIVES=12
COLLISION_PAIRS=6
BUDGET=12


def source(rng:random.Random,family:str)->tuple[int,...]:
    """Exact normalized integer unit series through degree 32."""
    if family in KNOWN:return old.source(rng,family)
    if family=='twisted_product':
        f=old.source(rng,'product')
        return tuple(v*(-1 if i%2 else 1) for i,v in enumerate(f))
    if family=='rational_product':
        return g.mul(old.source(rng,'product'),old.source(rng,'rational'))
    if family=='mixed_signed_product':
        return g.mul(old.source(rng,'signed'),old.source(rng,'product'))
    if family=='cubic_sparse':
        f=old.source(rng,'sparse')
        return g.mul(g.mul(f,f),f)
    raise ValueError('bad source family '+family)


def calibration():
    """Only RRC-19's 420 preexisting dev instances may train the gate."""
    return old.roster(include_test=False)['dev']


def case(rng,program,topology,split,family,index,*,mutate=False,pair=None):
    demos=[]
    for _ in range(2):
        f=source(rng,family)
        demos.append((f,t.execute(f,program,topology)))
    if mutate:
        f,y=demos[1]
        z=list(y);z[7]+=rng.choice((-3,-2,-1,1,2,3))
        demos[1]=(f,tuple(z))
    query=source(rng,family)
    return t.Case(f'{split}-{family}-{topology}-{index:05d}',split,topology,
                  tuple(demos),query,t.execute(query,program,topology),program,pair)


def roster(*,known_per=KNOWN_PER_TOPOLOGY,novel_per=NOVEL_PER_TOPOLOGY,
           negatives=NEGATIVES,pairs=COLLISION_PAIRS):
    """Test set independent of RRC-19 train/dev/test and paired within-set mutants.

    Source/graph selection is independent of network scores and query futures.
    Negative selection uses *observed* exact grammar rejection only.
    """
    if min(known_per,novel_per,negatives,pairs)<1:raise ValueError('positive roster sizes')
    past=old.roster()
    seen={c.visible for cases in past.values() for c in cases}
    groups={f:[] for f in FAMILIES}
    groups['negative']=[];groups['collision']=[]
    def append(split,c,duplicate=False):
        if c.visible in seen and not duplicate:return False
        seen.add(c.visible);groups[split].append(c);return True
    for i,family in enumerate(FAMILIES):
        for k,topology in enumerate(t.TOPOLOGIES):
            rng=random.Random(SEED+333+i*911+k*37)
            target=known_per if family in KNOWN else novel_per
            attempts=0
            while sum(c.topology==topology for c in groups[family])<target:
                attempts+=1
                if attempts>1500*target:raise RuntimeError('source exhaustion '+family+' '+topology)
                p=rng.choice(g.GRAPHS)
                c=case(rng,p,topology,family,family,attempts)
                append(family,c)
    rng=random.Random(SEED+9044)
    attempts=0
    while len(groups['negative'])<negatives:
        attempts+=1
        if attempts>30000:raise RuntimeError('negative exhaustion')
        family=rng.choice(FAMILIES)
        top=rng.choice(t.TOPOLOGIES)
        c=case(rng,rng.choice(g.GRAPHS),top,'negative',family,attempts,mutate=True)
        if c.visible in seen or t.matching_graphs(c):continue
        append('negative',c)
    rng=random.Random(SEED+9951)
    for i in range(pairs):
        family=NOVEL[i%len(NOVEL)]
        top=t.TOPOLOGIES[i%len(t.TOPOLOGIES)]
        for attempt in range(3000):
            c=case(rng,rng.choice(g.GRAPHS),top,'collision',family,2*i,pair=f'pair-{i}')
            if append('collision',c):break
        else:raise RuntimeError('pair source exhaustion')
        changed=list(c.future);changed[t.PREFIX+3]+=(-1 if i%2 else 1)
        alternate=replace(c,identifier=f'collision-{family}-{top}-{2*i+1:05d}',
                          future=tuple(changed),hidden_graph=None)
        assert append('collision',alternate,duplicate=True)
    return groups


def digest(cases):
    payload=[(c.identifier,c.family,c.topology,c.demos,c.query,c.future,c.hidden_graph,c.pair)
             for c in cases]
    return sha256(json.dumps(payload,separators=(',',':')).encode()).hexdigest()

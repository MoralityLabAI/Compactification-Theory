"""DCF-21: does escalate-on-abstention generalise beyond the DCF-20 mesh?

Domain A (primary, fresh instances): the ten DCF-14 graph families, generated by
DCF-14's run_instance with new seeds, at DCF-14's budgets (2^10, 2^14, 2^18 counted
operations) and penalties (4, 9). Policies, all from the same per-instance receipts:

  escalate          BP at the budget; if BP acts, use its action. If BP abstains (or
                    could not run), run the cheapest exact operator if BP ops + exact ops
                    fit the budget, else abstain. No tunable parameter.
  exact_else_mbe    DCF-14's strongest hand policy (selected on DCF-14 development data)
  exact_else_bp, exact_or_abstain, always_bp, abstain

Objective: verified expected utility - lambda * ops / 2^B.

Domain B (secondary, descriptive): the committed DCF-16 held-out records, scored with
the same policy from each record's operator list. These records were already used for
the EvalMath baseline, so this is a reuse of opened data.

Usage: python escalate21.py run | report
"""
import gzip
import json
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / 'dcf14_width_routing'))
import fg  # noqa: E402
import width14 as W14  # noqa: E402

P = json.loads((ROOT / 'PROTOCOL.json').read_text())
EXACT = W14.EXACT_METHODS
BASELINES = ['exact_else_mbe', 'exact_else_bp', 'exact_or_abstain', 'always_bp']


def specs():
    out = []
    for block in P['blocks']:
        for fam in block['families']:
            for n in block['sizes']:
                for s in range(block['seeds']):
                    out.append(dict(family=fam, n=n, seed=block['seed_base'] + 1000 * s + n, noise=('low', 'high')[s % 2],
                                    query_size=1 + s % 3, misspec=(s % 3 == 2) and fam != 'xor_noiseless'))
    return out


def escalate(rec, B, pen):
    """Returns (expected utility, ops, path) for escalate-on-abstention."""
    m = rec['methods']
    cap = 2 ** B
    bp = m.get(f'bp_B{B}')
    used = 0
    if bp is not None and bp.get('p') is not None:
        used = bp['ops']
        a = fg.decide(bp['p'], pen)
        if a >= 0:
            return fg.expected_utility(a, rec['reference'], pen), used, 'bp'
    ex = [(m[k]['ops'], k) for k in EXACT if k in m and used + m[k]['ops'] <= cap]
    if not ex:
        return 0.0, used, 'abstain'
    ops, k = min(ex)
    a = fg.decide(m[k]['p'], pen)
    return fg.expected_utility(a, rec['reference'], pen), used + ops, 'exact'


def baseline(rec, B, pen, pol):
    if pol == 'abstain':
        return 0.0, 0
    u, ops, _, _ = W14.policy_value(rec, B, pen, pol, {})
    return u, ops


def flag_stats(recs):
    """Recall/precision of 'BP abstains' as a flag for BP/exact decision changes."""
    n = changes = flagged = hit = 0
    per_family = {}
    for r in recs:
        for B in P['budgets']:
            bp = r['methods'].get(f'bp_B{B}')
            if bp is None or bp.get('p') is None:
                continue
            for pen in P['penalties']:
                a_bp = fg.decide(bp['p'], pen)
                a_ex = fg.decide(r['reference'], pen)
                ch, fl = a_bp != a_ex, a_bp < 0
                n += 1
                changes += ch
                flagged += fl
                hit += ch and fl
                f = per_family.setdefault(r['spec']['family'], [0, 0, 0, 0])
                f[0] += 1
                f[1] += ch
                f[2] += fl
                f[3] += ch and fl
    return dict(decisions=n, changes=changes, flagged=flagged, changes_flagged=hit,
                recall=hit / changes if changes else None, precision=hit / flagged if flagged else None,
                per_family={k: dict(decisions=v[0], changes=v[1], flagged=v[2], changes_flagged=v[3],
                                    recall=v[3] / v[1] if v[1] else None) for k, v in per_family.items()})


def run():
    with Pool(P['workers']) as pool:
        recs = pool.map(W14.run_instance, specs(), chunksize=1)
    raw = json.dumps(dict(protocol=P, records=recs), separators=(',', ':')).encode()
    with gzip.GzipFile(ROOT / 'receipt21.json.gz', 'wb', mtime=0) as f:
        f.write(raw)
    print(len(recs), 'instances;', sum(r['verified'] for r in recs), 'verified')


def domain_b():
    path = ROOT.parent / 'dcf16_decision_curriculum' / 'data' / 'heldout.jsonl.gz'
    rows = [json.loads(line) for line in gzip.open(path, 'rt')]
    out = {k: [] for k in ('escalate', 'symbolic', 'always_bp')}
    for e in rows:
        B = e['budget_log2_ops']
        pen = -e['decision_rule']['reward']['wrong']
        ref = e['verification']['reference_p']
        ops = {o['name']: o for o in e['operators']}
        cap = 2 ** B
        # symbolic = EvalMath reference predictor: cheapest exact within budget, else mbe, else abstain
        ex = sorted([(o['ops'], o) for o in e['operators'] if o['exact'] and o['within_budget']], key=lambda t: t[0])
        if ex:
            s_ops, o = ex[0]
            s_a = fg.decide(o['p'], pen)
        elif 'mbe' in ops and ops['mbe']['within_budget'] and ops['mbe']['p'] is not None:
            s_ops, s_a = ops['mbe']['ops'], fg.decide(ops['mbe']['p'], pen)
        else:
            s_ops, s_a = 0, -1
        out['symbolic'].append((fg.expected_utility(s_a, ref, pen), s_ops))
        bp = ops.get('bp')
        if bp is not None and bp['within_budget'] and bp['p'] is not None:
            b_a = fg.decide(bp['p'], pen)
            out['always_bp'].append((fg.expected_utility(b_a, ref, pen), bp['ops']))
            used = bp['ops']
        else:
            b_a, used = -1, 0
            out['always_bp'].append((0.0, 0))
        if b_a >= 0:
            out['escalate'].append((fg.expected_utility(b_a, ref, pen), used))
        else:
            ex2 = sorted([(o['ops'], o) for o in e['operators'] if o['exact'] and used + o['ops'] <= cap], key=lambda t: t[0])
            if ex2:
                o = ex2[0][1]
                out['escalate'].append((fg.expected_utility(fg.decide(o['p'], pen), ref, pen), used + o['ops']))
            else:
                out['escalate'].append((0.0, used))
    return {k: dict(eu=float(np.mean([u for u, _ in v])), mean_ops=float(np.mean([o for _, o in v])), n=len(v)) for k, v in out.items()}


def report():
    recs = json.loads(gzip.open(ROOT / 'receipt21.json.gz', 'rt').read())['records']
    ver = [r for r in recs if r['verified']]
    pols = ['escalate', 'abstain'] + BASELINES
    cond = {}
    for r in ver:
        for B in P['budgets']:
            for pen in P['penalties']:
                key = (r['spec']['family'], r['spec']['n'], B, pen)
                vals = {}
                u, ops, path = escalate(r, B, pen)
                vals['escalate'] = (u, ops, path)
                for pol in ['abstain'] + BASELINES:
                    vals[pol] = baseline(r, B, pen, pol)
                cond.setdefault(key, []).append(vals)
    res = dict(n_instances=len(recs), n_verified=len(ver), conditions=len(cond), flag=flag_stats(ver), by_lambda={})
    for lam in P['lambdas']:
        def objective(v, B):
            return v[0] - lam * v[1] / 2 ** B
        per = {}
        for key, items in cond.items():
            B = key[2]
            per[key] = {p: float(np.mean([objective(it[p], B) for it in items])) for p in pols}
        e1w = sum(v['escalate'] > v['exact_else_mbe'] + 1e-12 for v in per.values())
        e1l = sum(v['escalate'] < v['exact_else_mbe'] - 1e-12 for v in per.values())
        bw = sum(v['escalate'] > max(v[p] for p in pols if p != 'escalate') + 1e-12 for v in per.values())
        bl = sum(v['escalate'] < max(v[p] for p in pols if p != 'escalate') - 1e-12 for v in per.values())
        res['by_lambda'][str(lam)] = dict(
            mean={p: float(np.mean([v[p] for v in per.values()])) for p in pols},
            vs_exact_else_mbe=dict(wins=e1w, losses=e1l, ties=len(per) - e1w - e1l),
            vs_best_alternative=dict(wins=bw, losses=bl, ties=len(per) - bw - bl),
            by_family={f: {p: float(np.mean([v[p] for k, v in per.items() if k[0] == f])) for p in pols} for f in sorted({k[0] for k in per})})
    allv = [it for items in cond.values() for it in items]
    res['escalate_paths'] = {k: sum(it['escalate'][2] == k for it in allv) for k in ('bp', 'exact', 'abstain')}
    res['mean_ops'] = {p: float(np.mean([it[p][1] for it in allv])) for p in pols}
    res['mean_eu'] = {p: float(np.mean([it[p][0] for it in allv])) for p in pols}
    f = res['flag']
    l0 = res['by_lambda'][str(P['gate_lambda'])]
    res['gates'] = dict(
        F1=dict(rule=P['gates']['F1'], recall=f['recall'], passed=f['recall'] is not None and f['recall'] >= 0.8),
        E1=dict(rule=P['gates']['E1'], **l0['vs_exact_else_mbe'], passed=l0['vs_exact_else_mbe']['wins'] > l0['vs_exact_else_mbe']['losses']),
        E2=dict(rule=P['gates']['E2'], per_lambda={k: v['vs_best_alternative'] for k, v in res['by_lambda'].items()},
                passed=any(v['vs_best_alternative']['wins'] > v['vs_best_alternative']['losses'] for v in res['by_lambda'].values())))
    res['domain_b_dcf16_heldout_descriptive'] = domain_b()
    (ROOT / 'results21.json').write_bytes((json.dumps(res, indent=1) + '\n').encode())
    print('flag', {k: f[k] for k in ('decisions', 'changes', 'flagged', 'changes_flagged', 'recall', 'precision')})
    for lam, v in res['by_lambda'].items():
        print(lam, {p: round(x, 4) for p, x in v['mean'].items()}, 'vs mbe', v['vs_exact_else_mbe'], 'vs best', v['vs_best_alternative'])
    print('paths', res['escalate_paths'], 'ops', {k: round(v) for k, v in res['mean_ops'].items()})
    print('gates', {k: v['passed'] for k, v in res['gates'].items()})
    print('domain B', res['domain_b_dcf16_heldout_descriptive'])


if __name__ == '__main__':
    {'run': run, 'report': report}[sys.argv[1]]()

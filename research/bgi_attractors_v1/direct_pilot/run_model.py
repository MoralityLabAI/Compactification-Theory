"""Run BGI-01D against genuine pinned Qwen2.5-0.5B CPU generation.

No model training, gradient update, external actions, or executing agent-authored
code. Scored scenarios are fictional turnstile requests. JSON policy changes
go through the independent finite-schema validator.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
from pathlib import Path

from evaluate import evaluate
from world import SEED, canonical_bytes, load_fixture

MODEL_ID = "Qwen/Qwen2.5-0.5B-Instruct"
MODEL_REVISION = "7ae557604adf67be50417f59c2c2f167def9a775"
HERE = Path(__file__).resolve().parent


class QwenProposer:
    def __init__(self):
        import torch
        import transformers
        from transformers import AutoModelForCausalLM, AutoTokenizer

        torch.set_num_threads(2)
        torch.manual_seed(SEED)
        torch.use_deterministic_algorithms(True)
        self.torch = torch
        self.versions = {"torch": torch.__version__,
                         "transformers": transformers.__version__,
                         "python": platform.python_version()}
        self.tokenizer = AutoTokenizer.from_pretrained(
            MODEL_ID, revision=MODEL_REVISION, trust_remote_code=False)
        self.model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, revision=MODEL_REVISION, torch_dtype=torch.float32,
            trust_remote_code=False).cpu().eval()
        self.cache: dict[str, tuple[str, dict]] = {}
        self.actual_forward_calls = 0
        self.cache_hits = 0

    def __call__(self, messages: list[dict], task_type: str) -> tuple[str, dict]:
        if task_type not in ("action", "patch"):
            raise ValueError("unsupported inference type")
        key = hashlib.sha256(canonical_bytes({
            "messages": messages, "task_type": task_type,
        })).hexdigest()
        if key in self.cache:
            self.cache_hits += 1
            raw, metadata = self.cache[key]
            return raw, {**metadata, "cached_identical_prompt": True}
        torch = self.torch
        tensor = self.tokenizer.apply_chat_template(
            messages, tokenize=True, add_generation_prompt=True,
            return_tensors="pt")
        if not isinstance(tensor, torch.Tensor):
            raise RuntimeError("tokenizer did not return a tensor")
        if tensor.shape[1] > 768:
            raise RuntimeError("prompt exceeds frozen input limit")
        with torch.inference_mode():
            output = self.model.generate(
                tensor, max_new_tokens=8 if task_type == "action" else 96,
                do_sample=False, num_beams=1,
                pad_token_id=self.tokenizer.eos_token_id)
        tokens = output[0, tensor.shape[1]:]
        raw = self.tokenizer.decode(tokens, skip_special_tokens=True).strip()
        self.actual_forward_calls += 1
        meta = {"input_tokens": int(tensor.shape[1]),
                "output_tokens": int(tokens.shape[0]),
                "model_forward": "deterministic_greedy_full_generation",
                "cached_identical_prompt": False, "request_sha256": key}
        self.cache[key] = (raw, meta)
        return raw, meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=Path,
                    default=HERE / "results" / "qwen05b_direct_policy_v1.json")
    args = ap.parse_args()
    meta, heldout, campaigns = load_fixture()
    print("BGI01D_FIXTURE_SHA256=" + meta["sha256_bytes"], flush=True)
    model = QwenProposer()
    result = evaluate(model, heldout, campaigns)
    payload = {
        "schema": "bgi01d-direct-pilot-v1",
        "status": "real CPU model generation with synthetic tasks and sandbox patches",
        "model_id": MODEL_ID, "model_revision": MODEL_REVISION,
        "model_weights_modified": False,
        "model_policy_updates": "free-form JSON patches generated by model, then externally validated",
        "control_runtime": "authored gates and independent external checkpoint",
        "fixture": meta, "seed": SEED, "versions": model.versions,
        "total_action_rows": len(result["traces"]),
        "total_update_campaigns": len(result["proposals"]),
        "actual_model_forward_calls": model.actual_forward_calls,
        "reused_identical_prompt_results": model.cache_hits,
        "inference_cache_entries": len(model.cache),
        "quality_gate": result["quality_gate"],
        "summary": result["summary"],
        "proposals": result["proposals"],
        "traces": result["traces"],
        "limitations": [
            "Cross-domain lab-access fixtures were authored by the investigator",
            "One pinned 0.5B model and one paired heldout set; no population inference",
            "Model-generated proposals come from a separate policy-maintenance query",
            "Mutations are to externally supplied JSON policy, never neural weights",
            "Independent gates and D checkpoint are scripted infrastructure, not emergent morality",
            "Repeated identical model prompts are memoized and disclosed in counts",
            "A passing baseline semantic gate does not establish general safety or internal values",
        ],
    }
    raw = canonical_bytes(payload)
    receipt = {"sha256": hashlib.sha256(raw).hexdigest(), "payload": payload}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(receipt, sort_keys=True, indent=2) + "\n",
                           encoding="utf-8")
    print("BGI01D_RECEIPT_SHA256=" + receipt["sha256"], flush=True)
    print("BGI01D_QUALITY_GATE=" + payload["quality_gate"]["status"], flush=True)
    print("BGI01D_INFERENCE_COUNTERS=" + json.dumps({
        "forwards": model.actual_forward_calls,
        "cache_hits": model.cache_hits, "rows": len(result["traces"]),
        "proposals": len(result["proposals"])}, sort_keys=True), flush=True)
    for p in result["proposals"]:
        print("BGI01D_PATCH=" + json.dumps({
            "campaign": p["campaign"], "update_raw": p["update_raw"],
            "update_parsed": p["update_parsed"],
            "recovery_raw": p["recovery_raw"],
            "recovery_parsed": p["recovery_parsed"],
            "accepted": p["accepted"]}, sort_keys=True), flush=True)
    print("BGI01D_SUMMARY_JSON=" + json.dumps(result["summary"], sort_keys=True),
          flush=True)


if __name__ == "__main__":
    main()
